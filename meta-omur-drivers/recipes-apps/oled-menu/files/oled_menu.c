static uint8_t framebuf[BUFSIZE];

static void fb_clear(void)
{
    memset(framebuf, 0, BUFSIZE);
}

/* Tek piksel yak */
static void fb_pixel(int x, int y, int on)
{
    if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return;
    if (on)
        framebuf[x + (y / 8) * WIDTH] |= (1 << (y % 8));
    else
        framebuf[x + (y / 8) * WIDTH] &= ~(1 << (y % 8));
}

/* Karakter çiz (5x7 font) */
static void fb_char(int x, int y, char c)
{
    int idx, cx, cy;
    if (c < 32 || c > 90) c = '?';
    idx = c - 32;
    for (cx = 0; cx < 5; cx++) {
        uint8_t col = font5x7[idx][cx];
        for (cy = 0; cy < 7; cy++) {
            if (col & (1 << cy))
                fb_pixel(x + cx, y + cy, 1);
        }
    }
}

/* String çiz */
static void fb_string(int x, int y, const char *str)
{
    while (*str) {
        fb_char(x, y, *str);
        x += 6; /* 5 pixel + 1 boşluk */
        str++;
    }
}

/* Yatay çizgi */
static void fb_hline(int x, int y, int w)
{
    int i;
    for (i = 0; i < w; i++)
        fb_pixel(x + i, y, 1);
}

/* Framebuffer'ı /dev/oled0'a yaz */
static int fb_flush(void)
{
    int fd = open(OLED_DEV, O_WRONLY);
    if (fd < 0) {
        perror("open " OLED_DEV);
        return -1;
    }
    write(fd, framebuf, BUFSIZE);
    close(fd);
    return 0;
}

/* Menü öğeleri */
static const char *menu_items[] = {
    "SETTINGS",
    "MUSIC",
    "SPEED",
    "ACCELERATION",
    "MOTOR ENABLE",
};
#define MENU_COUNT (sizeof(menu_items) / sizeof(menu_items[0]))

static void draw_menu(int selected)
{
    int i, y;

    fb_clear();

    /* Başlık */
    fb_string(20, 0, "DASHBOARD");
    fb_hline(0, 9, WIDTH);

    /* Menü öğeleri */
    for (i = 0; i < (int)MENU_COUNT; i++) {
        y = 12 + i * 10;

        if (i == selected) {
            /* Seçili öğe: '>' işareti ile */
            fb_char(0, y, '>');
            fb_string(8, y, menu_items[i]);
        } else {
            fb_string(8, y, menu_items[i]);
        }
    }

    fb_flush();
}

int main(int argc, char *argv[])
{
    int selected = 0;
    char input;

    printf("=== OLED Dashboard Menu ===\n");
    printf("Controls: w=up, s=down, q=quit\n\n");

    draw_menu(selected);

    while (1) {
        input = getchar();
        switch (input) {
        case 'w':
            if (selected > 0) selected--;
            draw_menu(selected);
            break;
        case 's':
            if (selected < (int)MENU_COUNT - 1) selected++;
            draw_menu(selected);
            break;
        case '\n':
            printf("Selected: %s\n", menu_items[selected]);
            break;
        case 'q':
            fb_clear();
            fb_string(30, 28, "GOODBYE");
            fb_flush();
            return 0;
        }
    }

    return 0;
}